// Generate pinned sRGB hue anchors and lightness corrections for each renderer.
// Build packages/npm before running this command with --write or --check.
import { readFile, writeFile } from 'node:fs/promises';
import { cusp, oklchToLinear } from '../packages/npm/dist/color-math.js';

const mode = process.argv[2];
if (!['--check', '--write'].includes(mode)) throw new Error('Expected --check or --write');
const round = n => Math.round(n * 10000) / 10000;
const chroma = (l, h, cap) => Math.min(cap, 0.7 * cusp(l, h));
const curve = [];
let length = 0;
let previous;
for (let h = 10; h <= 370; h++) {
  const c = chroma(0.77, h, 0.16);
  const angle = h * Math.PI / 180;
  const point = [c * Math.cos(angle), c * Math.sin(angle)];
  if (previous) length += Math.hypot(point[0] - previous[0], point[1] - previous[1]);
  curve.push(length);
  previous = point;
}
const anchors = [10];
for (let i = 1; i < 12; i++) {
  const desired = length * i / 12;
  const upper = curve.findIndex(value => value >= desired);
  anchors.push(round(9 + upper + (desired - curve[upper-1]) / (curve[upper] - curve[upper-1])));
}
anchors.push(370);

// Solve for the luminance of a neutral swatch at the same nominal lightness.
const biases = [[0.77, 0.16], [0.48, 0.19], [0.45, 0.16], [0.77, 0.19]].map(([nominal, cap]) =>
  Array.from({length: 12}, (_, index) => {
    const h = index * 30;
    let low = -0.08, high = 0.08;
    for (let i = 0; i < 24; i++) {
      const mid = (low + high) / 2;
      const l = nominal + mid;
      const [r,g,b] = oklchToLinear(l, chroma(l, h, cap), h);
      if (0.2126*r + 0.7152*g + 0.0722*b < nominal ** 3) low = mid;
      else high = mid;
    }
    return round((low + high) / 2);
  }));
const row = values => values.join(', ');
const header = 'Generated by tools/tune-tables.mjs.';
const kotlinRow = values => values.map(v => Number.isInteger(v) ? v.toFixed(1) : String(v)).join(', ');
const outputs = new Map([
  ['packages/swift/Sources/TextHue/Tables.swift', `// ${header}\nlet anchors: [Double] = [${row(anchors)}]\nlet biases: [[Double]] = [\n${biases.map(v => `    [${row(v)}],`).join('\n')}\n]\n`],
  ['packages/kotlin/src/main/kotlin/com/hustedev/texthue/Tables.kt', `// ${header}\npackage com.hustedev.texthue\n\ninternal val anchors = doubleArrayOf(${kotlinRow(anchors)})\ninternal val biases = arrayOf(\n${biases.map(v => `    doubleArrayOf(${kotlinRow(v)}),`).join('\n')}\n)\n`],
  ['packages/dart/lib/src/tables.dart', `// ${header}\nconst anchors = <double>[${row(anchors)}];\nconst biases = <List<double>>[\n${biases.map(v => `  [${row(v)}],`).join('\n')}\n];\n`],
  ['packages/npm/src/tables.ts', `// ${header}\nexport const anchors = [${row(anchors)}];\nexport const biases = [\n${biases.map(v => `  [${row(v)}],`).join('\n')}\n];\n`],
  ['packages/python/src/texthue/_tables.py', `# ${header}\n# fmt: off\nANCHORS = (${row(anchors)})\nBIASES = (\n${biases.map(v => `    (${row(v)}),`).join('\n')}\n)\n`],
  ['packages/go/tables.go', `// ${header}\npackage texthue\n\nvar anchors = [...]float64{${row(anchors)}}\nvar biases = [...][12]float64{\n${biases.map(v => `\t{${row(v)}},`).join('\n')}\n}\n`],
]);
for (const [file, source] of outputs) {
  const path = new URL(`../${file}`, import.meta.url);
  if (mode === '--write') await writeFile(path, source);
  else if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== source) throw new Error(`Stale table: ${file}`);
}
