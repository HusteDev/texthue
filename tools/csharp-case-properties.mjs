import {writeFileSync} from 'node:fs';

// .NET's Rune API lacks these two derived properties used by Final_Sigma.
if (process.versions.unicode !== '17.0') throw Error('Expected Unicode 17.0');
const lines = ['// Generated by tools/csharp-case-properties.mjs using Unicode 17.0.', 'namespace TextHue;', '', 'internal static class CaseProperties', '{'];
for (const [name, property] of [['Cased', /\p{Cased}/u], ['Ignorable', /\p{Case_Ignorable}/u]]) {
  const boundaries = [];
  let inside = false;
  for (let code = 0; code <= 0x10ffff; code++) {
    const match = property.test(String.fromCodePoint(code));
    if (match !== inside) boundaries.push(code);
    inside = match;
  }
  lines.push(`    internal static readonly int[] ${name} = [`);
  for (let i = 0; i < boundaries.length; i += 12)
    lines.push('        ' + boundaries.slice(i, i + 12).map(x => '0x' + x.toString(16)).join(', ') + ',');
  lines.push('    ];');
}
lines.push('}', '');
writeFileSync(new URL('../packages/csharp/src/TextHue/CaseProperties.cs', import.meta.url), lines.join('\n'));
